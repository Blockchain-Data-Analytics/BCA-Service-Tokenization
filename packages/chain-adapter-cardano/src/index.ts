// ChainAdapter implementation for the Cardano/Aiken contract backend
// (bca-token-plutus/, moves to contracts/cardano/ in plan-reorg.md §8 step 3).
//
// Built on the `add-bca-provider` branch of the Evolution SDK fork
// (code.blockchain-applied.com/BCA/evolution-sdk), published to the BCA
// Forgejo npm registry as `@bca/evolution-sdk` and imported here under the
// alias `evolution-sdk-bca` — see package.json and this package's README.
// This is a different, newer SDK generation than `@lucid-evolution/lucid`
// (Promise-based, Blockfrost-only) that this file used until
// plan-plutus-tokenization.md's first live preprod deployment proved the
// fork's `BlockchainAppliedProvider` works end-to-end against BCA's own
// API — no Blockfrost dependency needed.
//
// Scope (plan-reorg.md §6.3 steps 3-4, updated by
// plan-plutus-tokenization.md): `deploySellerFactory` against
// `root_factory.ak`, and `deposit`/`withdraw`/`stop`/`getInstanceState`
// against `instance.ak`'s `service_instance` validator — the four redeemers
// proven on preprod in plan-plutus-tokenization.md. `defineService` and
// `openInstance` remain explicit stubs: `service.ak` (the `newInstance()`
// equivalent that actually creates an instance UTxO with its state-thread
// token) doesn't exist yet, so there is no on-chain way to open a new
// instance or enumerate a seller's services yet.
import {
  Address as CardanoAddress,
  Assets as CardanoAssets,
  Client,
  Data,
  InlineDatum,
  KeyHash,
  PlutusV3,
  Script as ScriptNS,
  type Chain,
} from "evolution-sdk-bca";
type Script = ScriptNS.Script;

// Our own wallet is always a plain payment-key address (generated via
// PrivateKey, never a script wallet) — `addSigner()` needs a precise
// `KeyHash`, not the general `Credential` (KeyHash | ScriptHash) union the
// SDK's own address/credential types carry.
function expectKeyHash(cred: { _tag: string; hash: Uint8Array }): InstanceType<typeof KeyHash.KeyHash> {
  if (cred._tag !== "KeyHash") {
    throw new Error(`expected a KeyHash credential, got ${cred._tag}`);
  }
  return KeyHash.fromBytes(cred.hash);
}
import type {
  Address,
  ChainAdapter,
  ChainEvent,
  ContractRef,
  EventFilter,
  InstanceState,
  ServiceParams,
  TokenRef,
  TxHandle,
  Unsubscribe,
  WalletHandle,
} from "@bca/chain-adapter";
import { asAddress, asContractRef } from "@bca/chain-adapter";

type ReadClient = ReturnType<ReturnType<typeof Client.make>["withBlockchainApplied"]>;
type SigningClient = ReturnType<ReadClient["withCip30"]>;
type SignBuilderResult = Awaited<ReturnType<ReturnType<SigningClient["newTx"]>["build"]>>;
type SubmitBuilderResult = Awaited<ReturnType<SignBuilderResult["sign"]>>;

export interface CardanoAdapterConfig {
  chainId: string; // "cardano:preprod" | "cardano:mainnet" | "cardano:preview"
  chain: Chain; // evolution-sdk-bca's `preprod`/`mainnet`/`preview` chain preset
  api: {
    baseUrl: string; // e.g. "https://staging.blockchain-applied.com/api_preprod/v1"
    token?: string;
  };
  // output of `aiken blueprint apply` against
  // bca-token-plutus/validators/instance.ak's `service_instance`,
  // parameterized by (token_policy_id, token_asset_name) — see
  // plan-plutus-tokenization.md for how this blueprint is produced. Not
  // regenerated by this package; caller supplies the applied blueprint's
  // compiled code.
  instance: {
    compiledCodeHex: string;
    scriptAddress: string; // bech32, derived from the same applied blueprint
    tokenPolicyId: string;
    tokenAssetNameHex: string;
  };
  // output of `aiken blueprint apply` against `root_factory.ak`,
  // parameterized by bca_admin's key hash. Optional: only needed for
  // `deploySellerFactory`.
  rootFactory?: {
    compiledCodeHex: string;
    policyId: string;
    bcaAdminPkh: string;
  };
}

function notImplemented(method: string): never {
  throw new Error(
    `CardanoAdapter.${method}() is not implemented yet — service.ak (the ` +
      "newInstance()-equivalent instance creator) doesn't exist, so there is " +
      "no on-chain way to open a new instance or define a service yet. See " +
      "plan-plutus-tokenization.md.",
  );
}

function plutusV3Script(compiledCodeHex: string): Script {
  return new PlutusV3.PlutusV3({
    bytes: Uint8Array.from(Buffer.from(compiledCodeHex, "hex")),
  }) as Script;
}

// Instance datum field order, mirrors bca-token-plutus/lib/bca/types.ak's
// ServiceInstanceDatum (day_price, deposit, retracted, start_time, end_time,
// user, provider) — a single-constructor Plutus record, Constr index 0.
interface InstanceDatumFields {
  dayPrice: bigint;
  deposit: bigint;
  retracted: bigint;
  startTime: bigint;
  endTime: bigint;
  user: Uint8Array;
  provider: Uint8Array;
}

function decodeInstanceDatum(data: Data.Data): InstanceDatumFields {
  if (!Data.isConstr(data) || data.fields.length !== 7) {
    throw new Error("instance UTxO datum is not a ServiceInstanceDatum");
  }
  const [dayPrice, deposit, retracted, startTime, endTime, user, provider] = data.fields as [
    bigint,
    bigint,
    bigint,
    bigint,
    bigint,
    Uint8Array,
    Uint8Array,
  ];
  return { dayPrice, deposit, retracted, startTime, endTime, user, provider };
}

function encodeInstanceDatum(f: InstanceDatumFields): Data.Data {
  return Data.constr(0n, [
    Data.int(f.dayPrice),
    Data.int(f.deposit),
    Data.int(f.retracted),
    Data.int(f.startTime),
    Data.int(f.endTime),
    f.user,
    f.provider,
  ]);
}

// Cardano validity intervals are slot-granular (1 slot = 1s on preprod/
// mainnet) — the validator reads `now` as the tx's validity-range upper
// bound (see instance.ak's module doc comment), so this must be a
// whole-second-aligned value, and the SAME value must be used both as the
// tx's `validTo` and inside the datum the tx submits. An arbitrary
// millisecond timestamp drifts across the ms<->slot<->ms round-trip between
// the SDK and the ledger and fails phase-2 validation with an opaque,
// trace-less error. See plan-plutus-tokenization.md's "Gotcha" section —
// this cost real debugging time once already, don't reintroduce it.
function validityUpperBoundMs(windowSeconds = 600): bigint {
  return BigInt((Math.floor(Date.now() / 1000) + windowSeconds) * 1000);
}

export class CardanoAdapter implements ChainAdapter {
  readonly chainId: string;
  private readonly readClient: ReadClient;
  private readonly config: CardanoAdapterConfig;
  private readonly instanceScript: Script;
  private signingClient?: SigningClient;

  private constructor(readClient: ReadClient, config: CardanoAdapterConfig) {
    this.chainId = config.chainId;
    this.readClient = readClient;
    this.config = config;
    this.instanceScript = plutusV3Script(config.instance.compiledCodeHex);
  }

  static init(config: CardanoAdapterConfig): CardanoAdapter {
    const readClient = Client.make(config.chain).withBlockchainApplied({
      baseUrl: config.api.baseUrl,
      token: config.api.token,
    });
    return new CardanoAdapter(readClient, config);
  }

  private requireWallet(): SigningClient {
    if (!this.signingClient) {
      throw new Error("CardanoAdapter: call connectWallet() before any signing operation");
    }
    return this.signingClient;
  }

  async connectWallet(): Promise<WalletHandle> {
    // CIP-30 browser wallet (Eternl/Nami/Lace/...), the Cardano equivalent
    // of window.ethereum — see plan-reorg.md §6.2.
    const api = await (
      window as unknown as { cardano: Record<string, { enable(): Promise<unknown> }> }
    ).cardano.eternl.enable();
    this.signingClient = this.readClient.withCip30(api as never);
    const address = await this.signingClient.address();
    return { address: asAddress(CardanoAddress.toBech32(address)), chainId: this.chainId };
  }

  async getBalance(addr: Address, token: TokenRef): Promise<bigint> {
    const utxos = await this.readClient.getUtxos(CardanoAddress.fromBech32(addr));
    return utxos.reduce((sum, utxo) => sum + CardanoAssets.getByUnit(utxo.assets, token as unknown as string), 0n);
  }

  // Root factory: spend nothing but the seller's request, mint one
  // "seller factory" auth token named after the seller's key hash. Asset
  // name doubling as the on-chain key is the state-thread-token pattern
  // documented in plan-reorg.md §6.1 / bca-token-plutus/validators/root_factory.ak.
  // NOT exercised on preprod yet (unlike service_instance) — ported to this
  // SDK generation but unverified end-to-end, see plan-plutus-tokenization.md
  // §"Remaining steps".
  async deploySellerFactory(rootFactory: ContractRef, seller: Address): Promise<ContractRef> {
    if (!this.config.rootFactory) {
      throw new Error("deploySellerFactory: CardanoAdapterConfig.rootFactory not configured");
    }
    if (rootFactory !== (this.config.rootFactory.policyId as unknown as ContractRef)) {
      throw new Error(
        `deploySellerFactory: rootFactory ${rootFactory} does not match configured ` +
          `root_factory policy id ${this.config.rootFactory.policyId}`,
      );
    }
    const client = this.requireWallet();
    const sellerKeyHashBytes = CardanoAddress.getAddressDetails(seller)?.paymentCredential?.hash;
    if (!sellerKeyHashBytes) throw new Error(`deploySellerFactory: could not resolve key hash for ${seller}`);
    const sellerKeyHash = Buffer.from(sellerKeyHashBytes).toString("hex");

    const rootFactoryScript = plutusV3Script(this.config.rootFactory.compiledCodeHex);
    const assetUnit = this.config.rootFactory.policyId + sellerKeyHash;
    // OnboardSeller { seller: ByteArray } — single-field record, Constr index 0.
    const redeemer = Data.constr(0n, [Data.bytearray(sellerKeyHash)]);
    const bcaAdminKeyHash = KeyHash.fromBytes(
      Uint8Array.from(Buffer.from(this.config.rootFactory.bcaAdminPkh, "hex")),
    );

    const tx = await client
      .newTx()
      .attachScript({ script: rootFactoryScript })
      .mintAssets({ assets: CardanoAssets.fromRecord({ [assetUnit]: 1n }), redeemer })
      .addSigner({ keyHash: bcaAdminKeyHash })
      .build();
    const signed = await tx.sign();
    const txHash = await signed.submit();
    await client.awaitTx(txHash);

    // the minted asset unit *is* the ContractRef here: it's what off-chain
    // code scans for (by policy ID) to enumerate onboarded sellers, per the
    // state-thread-token pattern in plan-reorg.md §6.1. Deriving the
    // seller_factory's actual spendable script address additionally
    // requires seller_factory.ak to hold its own datum/UTxO, which — like
    // service.ak — isn't wired up yet (plan-reorg.md §6.3 step 4).
    return asContractRef(assetUnit);
  }

  defineService(_sellerFactory: ContractRef, _params: ServiceParams): Promise<ContractRef> {
    return notImplemented("defineService");
  }
  openInstance(_service: ContractRef, _client: Address): Promise<ContractRef> {
    return notImplemented("openInstance");
  }

  // Looks up the instance's current UTxO by scanning the shared
  // service_instance script address. Known limitation: this only works
  // correctly for a single open instance per script address — until
  // service.ak's state-thread-token pattern lands, there's no on-chain way
  // to distinguish multiple concurrent instances at the same script
  // address, so `instance: ContractRef` is currently ignored beyond
  // sanity-checking it matches the configured script address. Matches the
  // same constraint the plan-plutus-tokenization.md deploy scripts operated
  // under (single-instance-per-script-address smoke test only).
  private async findInstanceUtxo(instance: ContractRef) {
    if (instance !== (this.config.instance.scriptAddress as unknown as ContractRef)) {
      throw new Error(
        `instance ${instance} does not match configured service_instance script address ` +
          `${this.config.instance.scriptAddress} — multi-instance addressing needs service.ak's ` +
          "state-thread token, not implemented yet",
      );
    }
    const scriptAddr = CardanoAddress.fromBech32(this.config.instance.scriptAddress);
    const utxos = await this.readClient.getUtxos(scriptAddr);
    if (utxos.length !== 1) {
      throw new Error(
        `expected exactly 1 UTxO at service_instance script address, found ${utxos.length}`,
      );
    }
    const datumOption = utxos[0].datumOption;
    if (!datumOption || datumOption._tag !== "InlineDatum") {
      throw new Error(
        "instance UTxO has no inline datum — service_instance's spend logic requires one " +
          "(see validators/instance.ak's `expect InlineDatum(...)` on the continuing output)",
      );
    }
    return { scriptAddr, utxo: utxos[0], datum: decodeInstanceDatum(datumOption.data) };
  }

  private async spendInstance(
    instance: ContractRef,
    redeemer: Data.Data,
    nextFields: InstanceDatumFields,
  ): Promise<SubmitBuilderResult> {
    const client = this.requireWallet();
    const { scriptAddr, utxo } = await this.findInstanceUtxo(instance);
    const ownAddress = await client.address();
    const nextTokenQty = nextFields.deposit - nextFields.retracted;
    const unit = this.config.instance.tokenPolicyId + this.config.instance.tokenAssetNameHex;

    const tx = await client
      .newTx()
      .attachScript({ script: this.instanceScript })
      .collectFrom({ inputs: [utxo], redeemer })
      .addSigner({ keyHash: expectKeyHash(ownAddress.paymentCredential) })
      .payToAddress({
        address: scriptAddr,
        assets: CardanoAssets.fromRecord({ lovelace: 2_000_000n, [unit]: nextTokenQty }),
        datum: new InlineDatum.InlineDatum({ data: encodeInstanceDatum(nextFields) }),
        autoMinUtxo: true,
      })
      .setValidity({ to: nextFields.endTime !== 0n ? nextFields.endTime : validityUpperBoundMs() })
      .build();
    return tx.sign();
  }

  // MakeDeposit(amount) — see lib/bca/instance.ak's next_datum: starts the
  // clock on first deposit, otherwise just increases `deposit`.
  async deposit(instance: ContractRef, amount: bigint): Promise<TxHandle> {
    const { datum } = await this.findInstanceUtxo(instance);
    const now = validityUpperBoundMs();
    const redeemer = Data.constr(0n, [Data.int(amount)]);
    const next: InstanceDatumFields = {
      ...datum,
      deposit: datum.deposit + amount,
      startTime: datum.startTime === 0n ? now : datum.startTime,
    };
    const signed = await this.spendInstance(instance, redeemer, next);
    const txHash = await signed.submit();
    return { txHash: String(txHash) };
  }

  // WithdrawUser/WithdrawProvider(amount) — mirrors next_datum's dust-drain
  // auto-stop logic exactly (see lib/bca/instance.ak); day_price/day_ms
  // integer-divides to 0 at BCA1TEST's test day_price, so auto-stop only
  // fires on an exact zero-remainder drain for the `user` side, effectively
  // never for `provider` at these magnitudes — see
  // plan-plutus-tokenization.md's redeemer-lifecycle table for the reasoning.
  async withdraw(instance: ContractRef, amount: bigint, as: "client" | "seller"): Promise<TxHandle> {
    const { datum } = await this.findInstanceUtxo(instance);
    const now = validityUpperBoundMs();
    const dayMs = 86_400_000n;
    const calcTime = datum.endTime !== 0n ? datum.endTime : now;
    const dustThreshold = datum.dayPrice / dayMs;

    let redeemer: Data.Data;
    let next: InstanceDatumFields;
    if (as === "client") {
      const paid = ((calcTime - datum.startTime) * datum.dayPrice) / dayMs;
      const avail = paid >= datum.deposit ? 0n : datum.deposit - paid;
      const wouldStop = avail - amount <= dustThreshold;
      redeemer = Data.constr(1n, [Data.int(amount)]);
      next = {
        ...datum,
        deposit: datum.deposit - amount,
        endTime: wouldStop ? now : datum.endTime,
      };
    } else {
      const ticks = calcTime - datum.startTime;
      const bal1 = (ticks * datum.dayPrice) / dayMs;
      const available = datum.deposit - datum.retracted;
      const wouldStop = datum.deposit - datum.retracted - amount < dustThreshold;
      void (bal1 > available ? available : bal1); // avail, kept for parity with next_datum's shape
      redeemer = Data.constr(2n, [Data.int(amount)]);
      next = {
        ...datum,
        retracted: datum.retracted + amount,
        endTime: wouldStop ? now : datum.endTime,
      };
    }
    const signed = await this.spendInstance(instance, redeemer, next);
    const txHash = await signed.submit();
    return { txHash: String(txHash) };
  }

  // Stop — mirrors next_datum's Stop branch: sets end_time, rejected if
  // already stopped (validator-side; not re-checked here).
  async stop(instance: ContractRef): Promise<TxHandle> {
    const { datum } = await this.findInstanceUtxo(instance);
    const now = validityUpperBoundMs();
    const redeemer = Data.constr(3n, []);
    const next: InstanceDatumFields = { ...datum, endTime: now };
    const signed = await this.spendInstance(instance, redeemer, next);
    const txHash = await signed.submit();
    return { txHash: String(txHash) };
  }

  async getInstanceState(instance: ContractRef): Promise<InstanceState> {
    const { datum } = await this.findInstanceUtxo(instance);
    return {
      dayPrice: datum.dayPrice,
      deposit: datum.deposit,
      retracted: datum.retracted,
      startTime: Number(datum.startTime),
      endTime: Number(datum.endTime),
      userAddress: asAddress(Buffer.from(datum.user).toString("hex")),
      providerAddress: asAddress(Buffer.from(datum.provider).toString("hex")),
      tokenAddress: (this.config.instance.tokenPolicyId +
        this.config.instance.tokenAssetNameHex) as unknown as TokenRef,
    };
  }

  // No native event log like EVM (see plan-reorg.md §6.2) — polls UTxOs at
  // the given policy/address and diffs against previously seen state. Left
  // unimplemented: needs a defined "new vs changed" semantics once multiple
  // instances can exist at once (service.ak), not meaningful for the
  // current single-instance-per-address constraint.
  subscribeEvents(_filter: EventFilter, _cb: (e: ChainEvent) => void): Unsubscribe {
    notImplemented("subscribeEvents");
  }
}
